// চালানো: node --no-warnings tests/race_api_test.js   (নকল D1 = node:sqlite; আসল D1-এ এখনো চালানো হয়নি)
import { DatabaseSync } from 'node:sqlite'; import fs from 'node:fs';
import * as reg from '../functions/api/register.js'; import * as race from '../functions/api/race.js';
const db=new DatabaseSync(':memory:'); db.exec(fs.readFileSync(new URL('../db/schema.sql',import.meta.url),'utf8'));
const env={DB:{prepare(sql){ const st=db.prepare(sql); const ex=(a)=>({ async run(){ st.run(...a); return {success:true}; }, async first(){ return st.get(...a)||null; }, async all(){ return {results:st.all(...a)}; } }); return { ...ex([]), bind(...a){ return ex(a); } }; }}};
let pass=0,fail=0; const ok=(c,m)=>{ if(c){pass++;console.log('PASS',m);} else {fail++;console.log('FAIL',m);} };
const post=(h,body)=>h.onRequestPost({request:new Request('http://x/api',{method:'POST',body:JSON.stringify(body)}),env}).then(async r=>({s:r.status,j:await r.json()}));
const mk=async()=>{ const g=await post(reg,{guest:true}); return {id:g.j.id,token:g.j.token}; };
const R=(u,op,x={})=>post(race,{...u,op,...x});
const A=await mk(),B=await mk(),C=await mk();
ok((await R({id:A.id,token:'bad'},'quick',{level:1})).s===401,'ভুল token বাতিল');
const q1=await R(A,'quick',{level:3}); ok(q1.j.ok&&q1.j.room.code.length===5&&q1.j.players.length===1&&q1.j.room.status==='wait'&&q1.j.room.host,'দ্রুত ম্যাচ: কেউ না থাকলে নতুন রুম');
const code=q1.j.room.code;
ok(!('pid' in q1.j.players[0]),'অন্যের id প্রকাশ হয় না');
const q2=await R(B,'quick',{level:3,veh:7,col:'#22a447'}); ok(q2.j.players.find(x=>x.you).veh===7&&q2.j.players.find(x=>x.you).col==='#22a447'&&q2.j.players.find(x=>x.you).name.indexOf('\u0001')<0,'গাড়ি আর রং সংরক্ষিত, নামে কিছু মেশে না');
const q2b=q2; ok(q2.j.room.code===code&&q2.j.players.length===2,'দ্বিতীয়জন একই রুমে ঢোকে');
const qm=await R(C,'quick',{level:3,map:4}); ok(qm.j.room.code!==code&&qm.j.room.map===4,'ভিন্ন ম্যাপের জন্য আলাদা রুম');
const q3=await R(C,'quick',{level:5}); ok(q3.j.room.code!==code,'ভিন্ন লেভেলের জন্য আলাদা রুম');
let p=await R(A,'poll',{code,x:0}); ok(p.j.room.status==='wait'&&p.j.room.auto_in!==null,'২ জন হলে অটো-স্টার্ট কাউন্টডাউন শুরু');
db.exec("UPDATE race_rooms SET ready_at=ready_at-11000 WHERE code='"+code+"'");
p=await R(A,'poll',{code,x:0}); ok(p.j.room.status==='go'&&p.j.room.start_at>p.j.room.now,'১০ সেকেন্ড পর রেস শুরু (শুরুর সময় ভবিষ্যতে)');
const pb=await R(B,'poll',{code,x:812.6}); await R(A,'poll',{code,x:300});
p=await R(A,'poll',{code,x:350}); ok(p.j.players.find(x=>!x.you).x===813,'অন্যের অবস্থান দেখা যায়');
ok((await R(C,'poll',{code,x:1})).s===403,'রুমে না থাকলে poll নয়');
ok((await R(A,'fin',{code,time:2})).s===400,'অসম্ভব দ্রুত সময় বাতিল');
ok((await R(A,'fin',{code,time:41.234})).j.players.find(x=>x.you).fin===41.23,'শেষ করার সময় জমা');
await R(A,'fin',{code,time:30}); p=await R(B,'poll',{code,x:900}); ok(p.j.players.find(x=>!x.you).fin===41.23,'প্রথম জমা করা সময়ই টিকে থাকে');
await R(B,'dnf',{code}); p=await R(A,'poll',{code,x:900}); ok(p.j.players.find(x=>!x.you).fin===-1,'বাদ পড়া চিহ্নিত');
ok((await R(C,'join',{code})).s===409,'শুরু হয়ে গেলে ঢোকা যায় না');
// ব্যক্তিগত রুম
const pr=await R(A,'create',{level:2,maxp:3,pub:0}); const pc=pr.j.room.code;
ok(pr.j.ok&&pr.j.room.pub===0,'ব্যক্তিগত রুম বানানো');
ok((await R(B,'quick',{level:2})).j.room.code!==pc,'দ্রুত ম্যাচ ব্যক্তিগত রুমে ঢোকায় না');
ok((await R(C,'join',{code:'ZZZZZ'})).s===404,'ভুল কোডে ত্রুটি');
ok((await R(C,'join',{code:pc.toLowerCase()})).j.players.length===2,'কোড দিয়ে যোগ (ছোট হাতের অক্ষরেও)');
ok((await R(C,'start',{code:pc})).s===403,'হোস্ট ছাড়া শুরু করা যায় না');
const st=await R(A,'start',{code:pc}); ok(st.j.room.status==='go','হোস্ট শুরু করে');
const solo=await R(B,'create',{level:1,maxp:4,pub:0}); ok((await R(B,'start',{code:solo.j.room.code})).s===400,'একা থাকলে শুরু হয় না');
const lv=await R(B,'leave',{code:solo.j.room.code}); ok(lv.j.ok,'রুম ছাড়া');
ok((await post(race,{id:A.id,token:A.token,op:'x',code:pc})).s===400,'অজানা কাজ বাতিল');
console.log(`\n${pass} পাস, ${fail} ফেল`); process.exit(fail?1:0);
